const STORAGE_KEY = "lp-lang";

function readSaved(): LangCode {
  if (typeof window === "undefined") return "en";
  const raw = window.localStorage.getItem(STORAGE_KEY);
  if (raw && LANGUAGES.some((l) => l.code === raw)) return raw as LangCode;
  return "en";
}

type Ctx = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (k: TranslationKey, vars?: Record<string, string | number>) => string;
};
const LangContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");
  // Read from storage after mount to avoid SSR hydration mismatch.
  useEffect(() => { setLangState(readSaved()); }, []);

  useEffect(() => {
    if (typeof document === "undefined") return;
    const meta = LANGUAGES.find((l) => l.code === lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = meta?.dir === "rtl" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try { window.localStorage.setItem(STORAGE_KEY, l); } catch { /* ignore */ }
  }, []);

  const t = useCallback((k: TranslationKey, vars?: Record<string, string | number>) => {
    const row = DICT[lang] as Record<string, string | undefined>;
    let s = row[k] ?? EN[k] ?? k;
    if (vars) {
      for (const [key, val] of Object.entries(vars)) {
        s = s.replaceAll(`{${key}}`, String(val));
      }
    }
    return s;
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang(): Ctx {
  const ctx = useContext(LangContext);
  if (ctx) return ctx;
  // Safe fallback so components mounted outside a provider still render.
  return {
    lang: "en",
    setLang: () => {},
    t: (k, vars) => {
      let s = EN[k] ?? k;
      if (vars) for (const [key, val] of Object.entries(vars)) s = s.replaceAll(`{${key}}`, String(val));
      return s;
    },
  };
}

export function localeFor(lang: LangCode): string {
  switch (lang) {
    case "en": return "en-US";
    case "bn": return "bn-BD";
    case "zh": return "zh-CN";
    case "hi": return "hi-IN";
    case "es": return "es-ES";
    case "ar": return "ar-SA";
    case "pt": return "pt-PT";
    case "ru": return "ru-RU";
    case "ur": return "ur-PK";
  }
}